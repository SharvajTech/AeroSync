-- ============================================================================
-- AeroSync Stage 1 - hybrid airport + flight operational network (PostgreSQL)
--
-- Adds the normalized operational tables next to the existing Hibernate-managed
-- tables (flights, crew, disruptions, gates). Nothing is dropped, renamed or
-- recreated:
--   * airports, aircraft, flight_schedules, flight_instances and
--     flight_dependencies are new tables;
--   * gates (existing) is extended in place with airport_id and status.
-- Existing databases are baselined at version 0 by Flyway
-- (spring.flyway.baseline-on-migrate) and then migrated forward.
--
-- All timestamps are TIMESTAMPTZ and written as UTC instants by the
-- application. Each airport keeps its IANA time zone for local display only.
-- ============================================================================

-- ── gates (existing table) ─────────────────────────────────────────────────
-- On a brand-new database Flyway runs before Hibernate creates the legacy
-- tables, so create gates here with exactly the columns Hibernate maps for
-- com.aerosync.model.Gate. On existing databases this statement is a no-op.
CREATE TABLE IF NOT EXISTS gates (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    available         BOOLEAN,
    compatible_types  VARCHAR(255),
    current_flight_id VARCHAR(255),
    gate_number       VARCHAR(255),
    terminal          VARCHAR(255)
);

-- ── airports ────────────────────────────────────────────────────────────────
CREATE TABLE airports (
    airport_id   UUID             NOT NULL,
    iata_code    VARCHAR(3)       NOT NULL,
    airport_name VARCHAR(120)     NOT NULL,
    city         VARCHAR(80)      NOT NULL,
    timezone     VARCHAR(64)      NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    status       VARCHAR(20)      NOT NULL DEFAULT 'OPERATIONAL',
    CONSTRAINT pk_airports PRIMARY KEY (airport_id),
    CONSTRAINT uk_airports_iata_code UNIQUE (iata_code),
    CONSTRAINT ck_airports_iata_code CHECK (iata_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_airports_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_airports_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_airports_timezone CHECK (length(trim(timezone)) > 0),
    CONSTRAINT ck_airports_status CHECK (status IN ('OPERATIONAL', 'RESTRICTED', 'CLOSED'))
);
COMMENT ON TABLE airports IS 'Airport nodes of the operational network graph (graph id airport:<iata_code>).';
COMMENT ON COLUMN airports.timezone IS 'IANA time zone, used only to display UTC timestamps in local time.';

-- ── aircraft ────────────────────────────────────────────────────────────────
CREATE TABLE aircraft (
    aircraft_id        UUID        NOT NULL,
    registration       VARCHAR(10) NOT NULL,
    aircraft_type      VARCHAR(10) NOT NULL,
    operating_airline  VARCHAR(3)  NOT NULL,
    current_airport_id UUID,
    status             VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    data_origin        VARCHAR(20) NOT NULL,
    CONSTRAINT pk_aircraft PRIMARY KEY (aircraft_id),
    CONSTRAINT uk_aircraft_registration UNIQUE (registration),
    CONSTRAINT fk_aircraft_current_airport FOREIGN KEY (current_airport_id) REFERENCES airports (airport_id),
    CONSTRAINT ck_aircraft_airline CHECK (operating_airline ~ '^([A-Z][A-Z0-9]|[0-9][A-Z])$'),
    CONSTRAINT ck_aircraft_status CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'GROUNDED', 'RETIRED')),
    CONSTRAINT ck_aircraft_data_origin CHECK (data_origin IN ('SYNTHETIC', 'IMPORTED', 'MANUAL'))
);
CREATE INDEX idx_aircraft_current_airport ON aircraft (current_airport_id);
COMMENT ON COLUMN aircraft.current_airport_id IS 'Last known position (for synthetic data: position at the start of the generated window).';

-- ── gates: extend in place ──────────────────────────────────────────────────
ALTER TABLE gates ADD COLUMN IF NOT EXISTS airport_id UUID;
ALTER TABLE gates ADD COLUMN IF NOT EXISTS status VARCHAR(20);
UPDATE gates SET status = 'OPEN' WHERE status IS NULL;
ALTER TABLE gates ALTER COLUMN status SET DEFAULT 'OPEN';
ALTER TABLE gates
    ADD CONSTRAINT fk_gates_airport FOREIGN KEY (airport_id) REFERENCES airports (airport_id);
ALTER TABLE gates
    ADD CONSTRAINT ck_gates_status CHECK (status IS NULL OR status IN ('OPEN', 'CLOSED', 'MAINTENANCE'));
-- Existing gates keep airport_id = NULL (NULLs never collide in a UNIQUE constraint).
ALTER TABLE gates
    ADD CONSTRAINT uk_gates_airport_terminal_gate UNIQUE (airport_id, terminal, gate_number);
COMMENT ON COLUMN gates.airport_id IS 'Owning airport; NULL for gates created before the operational network existed.';
COMMENT ON COLUMN gates.compatible_types IS 'Supported aircraft types, comma separated.';

-- ── flight_schedules ────────────────────────────────────────────────────────
-- One planned leg: a flight number on a service date from a departure airport.
-- Flight numbers repeat across dates; the leg key is
-- (flight_number, service_date, origin_airport_id).
CREATE TABLE flight_schedules (
    schedule_id            UUID        NOT NULL,
    flight_number          VARCHAR(8)  NOT NULL,
    origin_airport_id      UUID        NOT NULL,
    destination_airport_id UUID        NOT NULL,
    scheduled_departure    TIMESTAMPTZ NOT NULL,
    scheduled_arrival      TIMESTAMPTZ NOT NULL,
    operating_airline      VARCHAR(3)  NOT NULL,
    aircraft_type          VARCHAR(10) NOT NULL,
    service_date           DATE        NOT NULL,
    data_origin            VARCHAR(20) NOT NULL,
    CONSTRAINT pk_flight_schedules PRIMARY KEY (schedule_id),
    CONSTRAINT uk_flight_schedules_leg UNIQUE (flight_number, service_date, origin_airport_id),
    CONSTRAINT fk_flight_schedules_origin FOREIGN KEY (origin_airport_id) REFERENCES airports (airport_id),
    CONSTRAINT fk_flight_schedules_destination FOREIGN KEY (destination_airport_id) REFERENCES airports (airport_id),
    CONSTRAINT ck_flight_schedules_distinct_airports CHECK (origin_airport_id <> destination_airport_id),
    CONSTRAINT ck_flight_schedules_times CHECK (scheduled_arrival > scheduled_departure),
    CONSTRAINT ck_flight_schedules_block_time CHECK (scheduled_arrival - scheduled_departure <= INTERVAL '20 hours'),
    CONSTRAINT ck_flight_schedules_flight_number CHECK (flight_number ~ '^([A-Z][A-Z0-9]|[0-9][A-Z])[0-9]{1,4}[A-Z]?$'),
    CONSTRAINT ck_flight_schedules_airline CHECK (operating_airline ~ '^([A-Z][A-Z0-9]|[0-9][A-Z])$'),
    CONSTRAINT ck_flight_schedules_data_origin CHECK (data_origin IN ('SYNTHETIC', 'IMPORTED', 'MANUAL'))
);
CREATE INDEX idx_flight_schedules_service_date ON flight_schedules (service_date);
CREATE INDEX idx_flight_schedules_origin_departure ON flight_schedules (origin_airport_id, scheduled_departure);
CREATE INDEX idx_flight_schedules_destination_arrival ON flight_schedules (destination_airport_id, scheduled_arrival);
COMMENT ON COLUMN flight_schedules.service_date IS 'Local calendar date of departure at the origin airport.';

-- ── flight_instances ────────────────────────────────────────────────────────
-- The operating instance of a schedule (graph id flight:<flight_id>).
CREATE TABLE flight_instances (
    flight_id           UUID        NOT NULL,
    schedule_id         UUID        NOT NULL,
    aircraft_id         UUID,
    estimated_departure TIMESTAMPTZ,
    actual_departure    TIMESTAMPTZ,
    estimated_arrival   TIMESTAMPTZ,
    actual_arrival      TIMESTAMPTZ,
    delay_minutes       INTEGER     NOT NULL DEFAULT 0,
    status              VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    assigned_gate_id    BIGINT,
    version             BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT pk_flight_instances PRIMARY KEY (flight_id),
    CONSTRAINT uk_flight_instances_schedule UNIQUE (schedule_id),
    CONSTRAINT fk_flight_instances_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedules (schedule_id),
    CONSTRAINT fk_flight_instances_aircraft FOREIGN KEY (aircraft_id) REFERENCES aircraft (aircraft_id),
    CONSTRAINT fk_flight_instances_gate FOREIGN KEY (assigned_gate_id) REFERENCES gates (id),
    CONSTRAINT ck_flight_instances_delay CHECK (delay_minutes >= 0),
    CONSTRAINT ck_flight_instances_status CHECK (status IN
        ('SCHEDULED', 'DELAYED', 'BOARDING', 'DEPARTED', 'ARRIVED', 'CANCELLED', 'DIVERTED')),
    CONSTRAINT ck_flight_instances_estimated_times CHECK
        (estimated_arrival IS NULL OR estimated_departure IS NULL OR estimated_arrival > estimated_departure),
    CONSTRAINT ck_flight_instances_actual_times CHECK
        (actual_arrival IS NULL OR actual_departure IS NULL OR actual_arrival > actual_departure)
);
CREATE INDEX idx_flight_instances_aircraft ON flight_instances (aircraft_id);
CREATE INDEX idx_flight_instances_status ON flight_instances (status);
CREATE INDEX idx_flight_instances_gate ON flight_instances (assigned_gate_id);
COMMENT ON COLUMN flight_instances.version IS 'Optimistic-locking version (JPA @Version).';

-- ── flight_dependencies ─────────────────────────────────────────────────────
-- Operational flight -> flight dependencies, kept separate from the physical
-- DEPARTS_FROM / ARRIVES_AT relationships, which are derived from schedules.
CREATE TABLE flight_dependencies (
    dependency_id              UUID             NOT NULL,
    source_flight_id           UUID             NOT NULL,
    target_flight_id           UUID             NOT NULL,
    dependency_type            VARCHAR(32)      NOT NULL,
    impact_weight              DOUBLE PRECISION NOT NULL,
    minimum_connection_minutes INTEGER,
    metadata                   JSONB            NOT NULL DEFAULT '{}'::jsonb,
    active                     BOOLEAN          NOT NULL DEFAULT TRUE,
    data_origin                VARCHAR(20)      NOT NULL,
    CONSTRAINT pk_flight_dependencies PRIMARY KEY (dependency_id),
    CONSTRAINT uk_flight_dependencies_edge UNIQUE (source_flight_id, target_flight_id, dependency_type),
    CONSTRAINT fk_flight_dependencies_source FOREIGN KEY (source_flight_id) REFERENCES flight_instances (flight_id),
    CONSTRAINT fk_flight_dependencies_target FOREIGN KEY (target_flight_id) REFERENCES flight_instances (flight_id),
    CONSTRAINT ck_flight_dependencies_not_self CHECK (source_flight_id <> target_flight_id),
    CONSTRAINT ck_flight_dependencies_type CHECK (dependency_type IN
        ('AIRCRAFT_ROTATION', 'PASSENGER_CONNECTION', 'CREW_ROTATION', 'OPERATIONAL_CONSTRAINT')),
    CONSTRAINT ck_flight_dependencies_weight CHECK (impact_weight >= 0 AND impact_weight <= 1),
    CONSTRAINT ck_flight_dependencies_min_connection CHECK
        (minimum_connection_minutes IS NULL OR minimum_connection_minutes >= 0),
    CONSTRAINT ck_flight_dependencies_min_connection_required CHECK
        (dependency_type = 'OPERATIONAL_CONSTRAINT' OR minimum_connection_minutes IS NOT NULL),
    CONSTRAINT ck_flight_dependencies_metadata CHECK (jsonb_typeof(metadata) = 'object'),
    CONSTRAINT ck_flight_dependencies_data_origin CHECK (data_origin IN ('SYNTHETIC', 'IMPORTED', 'MANUAL'))
);
-- uk_flight_dependencies_edge already indexes source_flight_id (leading column).
CREATE INDEX idx_flight_dependencies_target_active ON flight_dependencies (target_flight_id) WHERE active;
COMMENT ON TABLE flight_dependencies IS 'Directed operational dependencies: a disruption of source_flight_id can affect target_flight_id.';
COMMENT ON COLUMN flight_dependencies.impact_weight IS '0..1 structural strength of the dependency (not a delay prediction).';
