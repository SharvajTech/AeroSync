/**
 * Builds the operational airport + flight graph from database records.
 *
 * <p>Read-only and separate from the GNN: the GNN keeps predicting cascade
 * risk from its own feature graph, while this service exposes the physical
 * network (DEPARTS_FROM / ARRIVES_AT) and the operational dependencies stored
 * in {@code flight_dependencies}.</p>
 */
@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class OperationalGraphService {

    public static final String SYNTHETIC_DATA_NOTICE =
            "Contains SYNTHETIC demonstration data generated by AeroSync; it is not real flight operations data.";

    public static final int MAX_FLIGHT_VIEW_DEPTH = 5;
    public static final int MAX_TRAVERSAL_DEPTH = 20;
    public static final int MAX_HORIZON_HOURS = 168;
    public static final int MAX_TRAVERSAL_FLIGHTS = 2_000;

    private static final int ID_CHUNK_SIZE = 1_000;

    private final AirportRepository airportRepository;
    private final FlightScheduleRepository flightScheduleRepository;
    private final FlightInstanceRepository flightInstanceRepository;
    private final FlightDependencyRepository flightDependencyRepository;

    /** Zone that defines "today" for the national network when no date is given. */
    @Value("${aerosync.operations.timezone:Asia/Kolkata}")
    private String operationsTimezone;

    /** All airports plus every flight operating on the service date, with their dependencies. */
    public GraphResponse getNationalNetwork(LocalDate serviceDate, boolean includeDependencies) {
        LocalDate day = serviceDate != null ? serviceDate : LocalDate.now(ZoneId.of(operationsTimezone));

        GraphBuilder builder = new GraphBuilder();
        airportRepository.findAllByOrderByIataCodeAsc()
                .forEach(airport -> builder.addAirport(OperationalRecordMapper.toRecord(airport)));
        List<FlightInstance> flights = flightInstanceRepository.findGraphFlightsByServiceDate(day);
        flights.forEach(flight -> builder.addFlight(OperationalRecordMapper.toRecord(flight)));
        if (includeDependencies && !flights.isEmpty()) {
            flightDependencyRepository.findActiveByServiceDate(day)
                    .forEach(dependency -> builder.addDependency(OperationalRecordMapper.toRecord(dependency)));
        }
        return response(GraphView.NATIONAL_NETWORK, null, day, dataWindow(), builder.build(), null);
    }

    /**
     * One airport with the flights departing from or arriving at it during the
     * local calendar day (airport time zone), their other endpoint airports and
     * the dependencies among those flights.
     */
    public GraphResponse getAirportGraph(String iataCode, LocalDate serviceDate, boolean includeDependencies) {
        Airport airport = requireAirport(iataCode);
        ZoneId zone = ZoneId.of(airport.getTimezone());
        LocalDate day = serviceDate != null ? serviceDate : LocalDate.now(zone);
        Instant windowStart = day.atStartOfDay(zone).toInstant();
        Instant windowEnd = day.plusDays(1).atStartOfDay(zone).toInstant();

        GraphBuilder builder = registeredAirportsBuilder();
        builder.includeAirport(airport.getIataCode());
        List<FlightInstance> flights =
                flightInstanceRepository.findAirportMovements(airport.getIataCode(), windowStart, windowEnd);
        flights.forEach(flight -> builder.addFlight(OperationalRecordMapper.toRecord(flight)));
        if (includeDependencies && !flights.isEmpty()) {
            Set<UUID> flightIds = new LinkedHashSet<>();
            flights.forEach(flight -> flightIds.add(flight.getFlightId()));
            for (List<UUID> chunk : chunks(flightIds)) {
                flightDependencyRepository.findActiveTouching(chunk)
                        .forEach(dependency -> builder.addDependency(OperationalRecordMapper.toRecord(dependency)));
            }
        }
        return response(GraphView.AIRPORT, NetworkIdentifiers.airportNodeId(airport.getIataCode()), day,
                dataWindow(), builder.build(), null);
    }

    /** A flight with its upstream and downstream dependencies up to {@code depth} hops. */
    public GraphResponse getFlightGraph(UUID flightId, int depth) {
        if (depth < 1 || depth > MAX_FLIGHT_VIEW_DEPTH) {
            throw new InvalidRequestParameterException(
                    "depth must be between 1 and " + MAX_FLIGHT_VIEW_DEPTH + ", was " + depth);
        }
        FlightInstance focus = requireFlight(flightId);
        Instant start = focus.getSchedule().getScheduledDeparture();
        DependencyTraversal.Options options =
                new DependencyTraversal.Options(depth, null, 0.0, null, MAX_TRAVERSAL_FLIGHTS);

        DependencyTraversal.Result upstream =
                DependencyTraversal.traverse(flightId, start, Direction.UPSTREAM, options, this::loadDependencies);
        DependencyTraversal.Result downstream =
                DependencyTraversal.traverse(flightId, start, Direction.DOWNSTREAM, options, this::loadDependencies);

        Set<UUID> flightIds = new LinkedHashSet<>();
        flightIds.add(flightId);
        flightIds.addAll(upstream.reachedFlightIds());
        flightIds.addAll(downstream.reachedFlightIds());
        Map<UUID, FlightRecord> flights = loadFlightRecords(flightIds);

        GraphBuilder builder = registeredAirportsBuilder();
        flights.values().forEach(builder::addFlight);
        upstream.traversedEdges().forEach(builder::addDependency);
        downstream.traversedEdges().forEach(builder::addDependency);

        TraversalDto traversal = new TraversalDto(
                depth, null, 0.0, List.of(DependencyType.values()), MAX_TRAVERSAL_FLIGHTS,
                upstream.truncated() || downstream.truncated(),
                upstream.depthLimitReached() || downstream.depthLimitReached(),
                toReach(upstream, flights),
                toReach(downstream, flights));
        return response(GraphView.FLIGHT, NetworkIdentifiers.flightNodeId(flightId),
                focus.getSchedule().getServiceDate(), null, builder.build(), traversal);
    }

    /**
     * Every flight reachable downstream from the given flight through active
     * dependencies (structural reachability; no delay is simulated).
     */
    public GraphResponse getAffectedFlights(UUID flightId, int maxDepth, Integer horizonHours,
                                            Set<DependencyType> types, double minImpactWeight, int maxFlights) {
        if (maxDepth < 1 || maxDepth > MAX_TRAVERSAL_DEPTH) {
            throw new InvalidRequestParameterException(
                    "max_depth must be between 1 and " + MAX_TRAVERSAL_DEPTH + ", was " + maxDepth);
        }
        if (horizonHours != null && (horizonHours < 1 || horizonHours > MAX_HORIZON_HOURS)) {
            throw new InvalidRequestParameterException(
                    "horizon_hours must be between 1 and " + MAX_HORIZON_HOURS + ", was " + horizonHours);
        }
        if (Double.isNaN(minImpactWeight) || minImpactWeight < 0.0 || minImpactWeight > 1.0) {
            throw new InvalidRequestParameterException(
                    "min_impact_weight must be between 0 and 1, was " + minImpactWeight);
        }
        if (maxFlights < 1 || maxFlights > MAX_TRAVERSAL_FLIGHTS) {
            throw new InvalidRequestParameterException(
                    "max_flights must be between 1 and " + MAX_TRAVERSAL_FLIGHTS + ", was " + maxFlights);
        }
        Set<DependencyType> followed = types == null || types.isEmpty()
                ? EnumSet.allOf(DependencyType.class)
                : EnumSet.copyOf(types);

        FlightInstance focus = requireFlight(flightId);
        DependencyTraversal.Options options = new DependencyTraversal.Options(maxDepth, followed, minImpactWeight,
                horizonHours == null ? null : Duration.ofHours(horizonHours), maxFlights);
        DependencyTraversal.Result downstream = DependencyTraversal.traverse(flightId,
                focus.getSchedule().getScheduledDeparture(), Direction.DOWNSTREAM, options, this::loadDependencies);

        Set<UUID> flightIds = new LinkedHashSet<>();
        flightIds.add(flightId);
        flightIds.addAll(downstream.reachedFlightIds());
        Map<UUID, FlightRecord> flights = loadFlightRecords(flightIds);

        GraphBuilder builder = registeredAirportsBuilder();
        flights.values().forEach(builder::addFlight);
        downstream.traversedEdges().forEach(builder::addDependency);

        List<DependencyType> typeList = new ArrayList<>(followed);
        TraversalDto traversal = new TraversalDto(maxDepth, horizonHours, minImpactWeight, typeList, maxFlights,
                downstream.truncated(), downstream.depthLimitReached(), null, toReach(downstream, flights));
        return response(GraphView.AFFECTED_FLIGHTS, NetworkIdentifiers.flightNodeId(flightId),
                focus.getSchedule().getServiceDate(), null, builder.build(), traversal);
    }

    /** Parses a comma-separated list of dependency types (case-insensitive). */
    public static Set<DependencyType> parseDependencyTypes(String csv) {
        if (csv == null || csv.isBlank()) {
            return EnumSet.allOf(DependencyType.class);
        }
        Set<DependencyType> types = EnumSet.noneOf(DependencyType.class);
        for (String token : csv.split(",")) {
            String name = token.trim().toUpperCase(java.util.Locale.ROOT);
            if (name.isEmpty()) {
                continue;
            }
            try {
                types.add(DependencyType.valueOf(name));
            } catch (IllegalArgumentException ex) {
                throw new InvalidRequestParameterException("Unknown dependency type '" + token.trim()
                        + "'. Allowed: " + Arrays.toString(DependencyType.values()));
            }
        }
        return types.isEmpty() ? EnumSet.allOf(DependencyType.class) : types;
    }

    // ── helpers ──────────────────────────────────────────────────────────

    private Airport requireAirport(String iataCode) {
        String iata;
        try {
            iata = NetworkIdentifiers.normalizeIata(iataCode);
        } catch (IllegalArgumentException ex) {
            throw new InvalidRequestParameterException(ex.getMessage());
        }
        return airportRepository.findByIataCode(iata)
                .orElseThrow(() -> new ResourceNotFoundException("Airport " + iata + " not found"));
    }

    private FlightInstance requireFlight(UUID flightId) {
        return flightInstanceRepository.findGraphFlightById(flightId)
                .orElseThrow(() -> new ResourceNotFoundException("Flight instance " + flightId + " not found"));
    }

    private GraphBuilder registeredAirportsBuilder() {
        GraphBuilder builder = new GraphBuilder();
        airportRepository.findAll().forEach(airport -> builder.registerAirport(OperationalRecordMapper.toRecord(airport)));
        return builder;
    }

    private List<DependencyRecord> loadDependencies(Direction direction, Set<UUID> frontier) {
        List<DependencyRecord> records = new ArrayList<>();
        for (List<UUID> chunk : chunks(frontier)) {
            List<FlightDependency> rows = direction == Direction.DOWNSTREAM
                    ? flightDependencyRepository.findActiveOutgoing(chunk)
                    : flightDependencyRepository.findActiveIncoming(chunk);
            rows.forEach(row -> records.add(OperationalRecordMapper.toRecord(row)));
        }
        return records;
    }

    private Map<UUID, FlightRecord> loadFlightRecords(Set<UUID> flightIds) {
        Map<UUID, FlightRecord> records = new LinkedHashMap<>();
        for (List<UUID> chunk : chunks(flightIds)) {
            flightInstanceRepository.findGraphFlightsByIds(chunk)
                    .forEach(flight -> records.put(flight.getFlightId(), OperationalRecordMapper.toRecord(flight)));
        }
        return records;
    }

    private static List<FlightReachDto> toReach(DependencyTraversal.Result result, Map<UUID, FlightRecord> flights) {
        List<FlightReachDto> reach = new ArrayList<>(result.reached().size());
        for (DependencyTraversal.Reach r : result.reached()) {
            FlightRecord flight = flights.get(r.flightId());
            if (flight == null) {
                throw new GraphIntegrityException("Dependency " + r.via().dependencyId()
                        + " references missing flight instance " + r.flightId());
            }
            reach.add(new FlightReachDto(
                    NetworkIdentifiers.flightNodeId(flight.flightId()),
                    flight.flightId(),
                    flight.flightNumber(),
                    flight.serviceDate(),
                    flight.originIata(),
                    flight.destinationIata(),
                    flight.scheduledDeparture(),
                    r.depth(),
                    NetworkIdentifiers.flightNodeId(r.parentFlightId()),
                    NetworkIdentifiers.dependencyEdgeId(r.via().dependencyId()),
                    r.via().type(),
                    Math.round(r.pathImpactWeight() * 10_000.0) / 10_000.0));
        }
        return reach;
    }

    private DataWindowDto dataWindow() {
        LocalDate first = flightScheduleRepository.findFirstByOrderByServiceDateAsc()
                .map(FlightSchedule::getServiceDate).orElse(null);
        LocalDate last = flightScheduleRepository.findFirstByOrderByServiceDateDesc()
                .map(FlightSchedule::getServiceDate).orElse(null);
        return new DataWindowDto(first, last);
    }

    private static GraphResponse response(GraphView view, String focusNodeId, LocalDate serviceDate,
                                          DataWindowDto dataWindow, OperationalGraph graph, TraversalDto traversal) {
        return new GraphResponse(view, focusNodeId, serviceDate, dataWindow, graph.syntheticData(),
                graph.syntheticData() ? SYNTHETIC_DATA_NOTICE : null, traversal, graph.summary(),
                graph.nodes(), graph.edges());
    }

    private static List<List<UUID>> chunks(Set<UUID> ids) {
        List<UUID> all = new ArrayList<>(ids);
        List<List<UUID>> chunks = new ArrayList<>();
        for (int i = 0; i < all.size(); i += ID_CHUNK_SIZE) {
            chunks.add(all.subList(i, Math.min(all.size(), i + ID_CHUNK_SIZE)));
        }
        return chunks;
    }
}
